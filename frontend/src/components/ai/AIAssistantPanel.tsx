import { motion } from "framer-motion";
import { ArrowUp, BrainCircuit, MessageSquareText, X } from "lucide-react";
import { useEffect, useState } from "react";
import { api } from "../../api/client";
import type { Incident } from "../../types/incident";

interface Props { onClose: () => void; }
interface Message { id: string; role: "assistant" | "user"; content: string; sources?: string[]; }

export default function AIAssistantPanel({ onClose }: Props) {
  const [input, setInput] = useState("");
  const [messages, setMessages] = useState<Message[]>([{
    id: "welcome", role: "assistant",
    content: "Ask about an incident, its timeline, logs, metrics, deployments, or dependencies. Answers are generated by the backend using the selected incident's available context.",
  }]);
  const [incident, setIncident] = useState<Incident | null>(null);
  const [loadingIncident, setLoadingIncident] = useState(true);
  const [sending, setSending] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    api.getIncidents().then((items) => {
      if (cancelled) return;
      const active = items.find((item) => item.status !== "RESOLVED") ?? items[0] ?? null;
      setIncident(active);
      if (active) setMessages((current) => [...current, { id: "context", role: "assistant", content: `Current context: incident #${active.id} — ${active.title} (${active.service}).` }]);
    }).catch((err: unknown) => {
      if (!cancelled) setError(err instanceof Error ? err.message : "Could not load incident context.");
    }).finally(() => { if (!cancelled) setLoadingIncident(false); });
    return () => { cancelled = true; };
  }, []);

  async function sendMessage() {
    const value = input.trim();
    if (!value || sending) return;
    if (!incident) {
      setError("No incident is available to provide context. Create or ingest an incident first.");
      return;
    }
    setError(null);
    setInput("");
    setMessages((current) => [...current, { id: `user-${Date.now()}`, role: "user", content: value }]);
    setSending(true);
    try {
      const response = await api.askAssistant(incident.id, value);
      setMessages((current) => [...current, {
        id: `assistant-${Date.now()}`, role: "assistant", content: response.answer,
        sources: response.evidenceSources,
      }]);
    } catch (err) {
      const message = err instanceof Error ? err.message : "The AI assistant request failed.";
      setError(message);
      setMessages((current) => [...current, { id: `error-${Date.now()}`, role: "assistant", content: `I couldn't answer that request: ${message}` }]);
    } finally { setSending(false); }
  }

  return (
    <motion.div className="workspace-overlay justify-end" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }}>
      <motion.div initial={{ x: 50, opacity: 0 }} animate={{ x: 0, opacity: 1 }} exit={{ x: 50, opacity: 0 }} className="workspace-panel h-[92vh] w-full max-w-155">
        <div className="flex h-full flex-col">
          <div className="flex h-16 shrink-0 items-center justify-between border-b border-white/[0.07] px-5">
            <div className="flex items-center gap-3">
              <div className="grid h-8 w-8 place-items-center rounded-lg border border-emerald-400/15 bg-emerald-400/5 text-emerald-300"><BrainCircuit size={16} /></div>
              <div><p className="text-xs font-semibold text-white/80">AI Assistant</p><p className="text-[9px] text-white/25">{loadingIncident ? "Loading incident context…" : incident ? `Context: #${incident.id} · ${incident.service}` : "No incident context"}</p></div>
            </div>
            <button onClick={onClose} aria-label="Close AI assistant" className="grid h-8 w-8 place-items-center rounded-lg text-white/30 hover:bg-white/4 hover:text-white/70"><X size={17} /></button>
          </div>
          <div className="min-h-0 flex-1 overflow-y-auto p-5">
            <div className="space-y-4">
              {messages.map((message) => (
                <div key={message.id} className={message.role === "user" ? "ml-8 rounded-xl border border-emerald-400/10 bg-emerald-400/[0.035] p-4" : "mr-8 rounded-xl border border-white/6 bg-white/1.5 p-4"}>
                  <div className="flex gap-3">{message.role === "assistant" && <MessageSquareText size={15} className="mt-0.5 shrink-0 text-emerald-300" />}<div className="min-w-0"><p className="whitespace-pre-wrap text-xs leading-6 text-white/65">{message.content}</p>{message.sources?.length ? <p className="mt-2 text-[9px] text-white/25">Sources: {message.sources.join(", ")}</p> : null}</div></div>
                </div>
              ))}
              {sending && <p className="mr-8 rounded-xl border border-white/6 bg-white/1.5 p-4 text-xs text-white/35">Analyzing incident context…</p>}
            </div>
          </div>
          {error && <p role="alert" className="mx-4 mb-2 rounded-lg border border-red-500/20 bg-red-500/5 p-3 text-xs text-red-300">{error}</p>}
          <div className="border-t border-white/[0.07] p-4">
            <div className="flex items-end gap-2 rounded-xl border border-white/8 bg-black/20 p-2">
              <textarea value={input} onChange={(event) => setInput(event.target.value)} onKeyDown={(event) => { if (event.key === "Enter" && !event.shiftKey) { event.preventDefault(); void sendMessage(); } }} placeholder="Ask about production…" rows={2} disabled={loadingIncident || sending || !incident} className="min-h-13 flex-1 resize-none bg-transparent px-2 py-1 text-xs leading-5 text-white/75 outline-none placeholder:text-white/20 disabled:opacity-50" />
              <button onClick={() => void sendMessage()} disabled={!input.trim() || sending || loadingIncident || !incident} aria-label="Send question" className="grid h-9 w-9 shrink-0 place-items-center rounded-lg bg-emerald-400 text-[#032118] transition hover:bg-emerald-300 disabled:opacity-40"><ArrowUp size={16} /></button>
            </div>
            <p className="mt-2 text-center text-[9px] text-white/20">Answers use the backend's available incident evidence. The assistant cannot execute production changes.</p>
          </div>
        </div>
      </motion.div>
    </motion.div>
  );
}
